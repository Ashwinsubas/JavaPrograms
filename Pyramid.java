public class Pyramid {

    public static void main(String ar[])
    {

        for(int i=0;i<4;i++)
        {
            for(int j=0;j<=i;j++)
            {
                System.out.print("* ");  //Use print to print the * on the same line
            }

            System.out.println();  //for new line
        }
    }
    
}
